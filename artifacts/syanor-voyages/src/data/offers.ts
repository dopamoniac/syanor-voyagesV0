export function getOfferBySlug(slug: string): TravelOffer | undefined {
  return offers.find((o) => o.slug === slug);
}

export function getOffersByCategory(categories: TravelOffer["category"][]): TravelOffer[] {
  return offers.filter((o) => categories.includes(o.category));
}

export function getRelatedOffers(offer: TravelOffer, limit = 3): TravelOffer[] {
  const sameCat = offers.filter((o) => o.category === offer.category && o.slug !== offer.slug);
  const others = offers.filter((o) => o.category !== offer.category && o.slug !== offer.slug);
  return [...sameCat, ...others].slice(0, limit);
}

export function getOffersByMonth(monthSlug: string, year?: "2026" | "2027"): TravelOffer[] {
  return offers.filter(
    (o) => o.monthSlug === monthSlug && (year === undefined || o.year === year)
  );
}

export function getOffersByCity(citySlug: string): TravelOffer[] {
  return offers.filter((o) => o.cityTags?.includes(citySlug));
}


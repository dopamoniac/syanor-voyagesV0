export function getUpcomingOffers(limit?: number): TravelOffer[] {
  const dated = offers
    .filter((o) => (o.category === "Omra" || o.category === "Omra Plus") && o.monthSlug)
    .sort((a, b) => (DEPARTURE_ORDER[a.id] ?? 99) - (DEPARTURE_ORDER[b.id] ?? 99));
  return limit !== undefined ? dated.slice(0, limit) : dated;
}

export function getFeaturedOffers(limit = 4): TravelOffer[] {
  return offers.filter((o) => o.featured).slice(0, limit);
}
